// Pure: OpenAPI document → TypeScript source of the v3 tool input schemas (src/generated/v3-params.ts).

function resolveRef(spec, node) {
  let current = node;
  while (current && typeof current === "object" && typeof current.$ref === "string") {
    current = current.$ref
      .replace(/^#\//, "")
      .split("/")
      .reduce((value, key) => value?.[key], spec);
  }
  return current;
}

export function queryParams(spec, path) {
  const item = spec.paths[path];
  return [...(item.parameters ?? []), ...(item.get?.parameters ?? [])]
    .map((param) => resolveRef(spec, param))
    .filter((param) => param.in === "query")
    .map((param) => {
      const schema = resolveRef(spec, param.schema ?? {});
      return {
        name: param.name,
        required: param.required === true,
        type: schema.type,
        enum: schema.enum,
        minimum: schema.minimum,
        maximum: schema.maximum,
        default: schema.default,
        description: param.description ?? schema.description,
      };
    });
}

function zodFor(path, param) {
  let code;
  if (param.enum) {
    code = `z.enum(${JSON.stringify(param.enum)})`;
  } else if (param.type === "string") {
    code = "z.string()";
  } else if (param.type === "integer") {
    code = "z.number().int()";
  } else if (param.type === "number") {
    code = "z.number()";
  } else if (param.type === "boolean") {
    code = "z.boolean()";
  } else {
    throw new Error(`${path} ${param.name}: unsupported schema type ${JSON.stringify(param.type)} — extend scripts/params-source.mjs`);
  }
  if (param.minimum !== undefined) code += `.min(${param.minimum})`;
  if (param.maximum !== undefined) code += `.max(${param.maximum})`;
  if (!param.required) code += ".optional()";
  const text = param.description?.trim();
  const sentence = text && !/[.!?]$/.test(text) ? `${text}.` : text;
  const description = [sentence, param.default !== undefined ? `Default: ${param.default}.` : undefined]
    .filter(Boolean)
    .join(" ");
  if (description) code += `.describe(${JSON.stringify(description)})`;
  return code;
}

export function renderParams(spec) {
  const blocks = Object.keys(spec.paths).map((path) => {
    const lines = queryParams(spec, path).map((param) => `    ${JSON.stringify(param.name)}: ${zodFor(path, param)},`);
    return `  ${JSON.stringify(path)}: {\n${lines.join("\n")}\n  },`;
  });
  return [
    `// Generated by scripts/generate-params.mjs from spec/v3-openapi.json (v3 API ${spec.info.version}) — do not edit; run \`npm run gen:params\`.`,
    `import { z } from "zod";`,
    ``,
    `export const v3Params = {`,
    ...blocks,
    `} satisfies Record<string, z.ZodRawShape>;`,
    ``,
    `export type V3Path = keyof typeof v3Params;`,
    ``,
  ].join("\n");
}
